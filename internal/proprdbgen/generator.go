package proprdbgen

import (
	"errors"
	"fmt"
	"regexp"
	"sort"
	"strconv"
	"strings"

	proprdbpb "github.com/fingon/proprdb/proto/proprdb"
	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/reflect/protoreflect"
	descriptorpb "google.golang.org/protobuf/types/descriptorpb"
)

type projectedField struct {
	HashSchema                string
	Path                      []*protogen.Field
	ColumnName                string
	ProtoFieldName            string
	GetterName                string
	SQLiteType                string
	SQLiteDefault             string
	SchemaSignature           string
	IsOptional                bool
	LegacyOneofPresenceRepair bool
	SwiftPropertyName         string
	SwiftPresenceName         string
	SwiftOneofPropertyName    string
}

type messageIndex struct {
	ColumnNames []string
	IndexName   string
	Signature   string
}

type messageModel struct {
	GoName              string
	SwiftTypeName       string
	SwiftPropertyName   string
	TableName           string
	TypeName            string
	TableTypeName       string
	RowTypeName         string
	ProjectionSchema    string
	ProjectedFields     []projectedField
	Indexes             []messageIndex
	OmitSync            bool
	ValidateWrite       bool
	AllowCustomIDInsert bool
	ChangeListeners     bool
	QueryStatistics     bool
	DirtyWindows        []messageDirtyWindow
	DirtyKeys           []messageDirtyKeys
}

type messageDirtyKeys struct {
	Name           string
	WatchedColumns []string
}

type messageDirtyWindow struct{ Name, StartColumn, EndColumn string }

var dirtyWindowNamePattern = regexp.MustCompile(`^[a-z][a-z0-9_]*$`)

type modelCollector struct{}

type generatorEmitter struct {
	g *protogen.GeneratedFile
}

const (
	dataVariable           = "data"
	idColumn               = "id"
	atNSColumn             = "at_ns"
	errorReturnType        = "error"
	errNilDBTX             = "nil DBTX"
	errNilData             = "nil data"
	errEmptyID             = "empty id"
	projectionOptionalFlag = ":optional"
)

// GenerateFile generates proprdb CRUD code for one .proto file.
func GenerateFile(plugin *protogen.Plugin, file *protogen.File) error {
	return GenerateFiles(plugin, []*protogen.File{file})
}

func GenerateFiles(plugin *protogen.Plugin, files []*protogen.File) error {
	if len(files) == 0 {
		return nil
	}
	sort.Slice(files, func(left, right int) bool {
		return files[left].Desc.Path() < files[right].Desc.Path()
	})
	collector := modelCollector{}
	models := make([]messageModel, 0)
	for _, file := range files {
		fileModels, err := collector.collectModels(file)
		if err != nil {
			return err
		}
		models = append(models, fileModels...)
	}

	if len(models) == 0 {
		return nil
	}
	if err := validateModels(models); err != nil {
		return err
	}

	file := files[0]
	filename := file.GeneratedFilenamePrefix + ".proprdb.pb.go"
	g := plugin.NewGeneratedFile(filename, file.GoImportPath)
	needsProjectionReflection := false
	for _, model := range models {
		if model.hasOptionalProjectedFields() || model.hasPathProjectedFields() {
			needsProjectionReflection = true
		}
	}
	g.P("// Code generated by protoc-gen-proprdb. DO NOT EDIT.")
	g.P()
	g.P("package ", file.GoPackageName)
	g.P()
	g.P("import (")
	g.P(`"context"`)
	g.P(`"errors"`)
	g.P(`"fmt"`)
	g.P(`"io"`)
	g.P()
	g.P(`"google.golang.org/protobuf/proto"`)
	if needsProjectionReflection {
		g.P(`"google.golang.org/protobuf/reflect/protoreflect"`)
	}
	g.P(`rt "github.com/fingon/proprdb/rt"`)
	g.P(")")
	g.P()

	emitter := generatorEmitter{g: g}
	emitter.emitShared()
	for _, model := range models {
		emitter.emitModel(model)
	}
	emitter.emitWrapper(models)

	return nil
}

func validateModels(models []messageModel) error {
	symbolOwners := make(map[string]string)
	swiftSymbolOwners := make(map[string]string)
	tableOwners := make(map[string]string)
	for _, model := range models {
		if owner, exists := tableOwners[model.TableName]; exists {
			return fmt.Errorf("table %s is generated by both %s and %s", model.TableName, owner, model.TypeName)
		}
		tableOwners[model.TableName] = model.TypeName
		symbols := []string{model.GoName, model.TableTypeName, model.RowTypeName}
		if model.ChangeListeners {
			symbols = append(symbols, model.GoName+"Change")
		}
		for _, suffix := range []string{"TableName", "TypeName", "ProjectionSchema", "CreateTableSQL", "InsertSQL", "UpsertSQL"} {
			symbols = append(symbols, model.GoName+suffix)
		}
		for _, symbol := range symbols {
			if owner, exists := symbolOwners[symbol]; exists {
				return fmt.Errorf("generated symbol %s collides between %s and %s", symbol, owner, model.TypeName)
			}
			symbolOwners[symbol] = model.TypeName
		}
		for _, symbol := range []string{model.SwiftTypeName, model.SwiftPropertyName} {
			if owner, exists := swiftSymbolOwners[symbol]; exists {
				return fmt.Errorf("generated Swift symbol %s collides between %s and %s", symbol, owner, model.TypeName)
			}
			swiftSymbolOwners[symbol] = model.TypeName
		}
	}
	return nil
}

func modelsHaveChangeListeners(models []messageModel) bool {
	for _, model := range models {
		if model.ChangeListeners {
			return true
		}
	}
	return false
}

func (c modelCollector) collectModels(file *protogen.File) ([]messageModel, error) {
	models := make([]messageModel, 0)
	for _, message := range file.Messages {
		if err := c.appendMessageModels(&models, message); err != nil {
			return nil, err
		}
	}

	return models, nil
}

func (c modelCollector) appendMessageModels(models *[]messageModel, message *protogen.Message) error {
	if !message.Desc.IsMapEntry() {
		model, err := c.buildModel(message)
		if err != nil {
			return err
		}

		if model.GoName != "" {
			*models = append(*models, model)
		}
	}

	for _, nested := range message.Messages {
		if err := c.appendMessageModels(models, nested); err != nil {
			return err
		}
	}

	return nil
}

func (c modelCollector) buildModel(message *protogen.Message) (messageModel, error) {
	omitTable, err := c.messageOptionBool(message, proprdbpb.E_OmitTable)
	if err != nil {
		return messageModel{}, fmt.Errorf("message %s omit_table option: %w", message.Desc.FullName(), err)
	}
	if omitTable {
		return messageModel{}, nil
	}
	omitSync, err := c.messageOptionBool(message, proprdbpb.E_OmitSync)
	if err != nil {
		return messageModel{}, fmt.Errorf("message %s omit_sync option: %w", message.Desc.FullName(), err)
	}
	validateWrite, err := c.messageOptionBool(message, proprdbpb.E_ValidateWrite)
	if err != nil {
		return messageModel{}, fmt.Errorf("message %s validate_write option: %w", message.Desc.FullName(), err)
	}
	allowCustomIDInsert, err := c.messageOptionBool(message, proprdbpb.E_AllowCustomIdInsert)
	if err != nil {
		return messageModel{}, fmt.Errorf("message %s allow_custom_id_insert option: %w", message.Desc.FullName(), err)
	}
	changeListeners, err := c.messageOptionBool(message, proprdbpb.E_ChangeListeners)
	if err != nil {
		return messageModel{}, fmt.Errorf("message %s change_listeners option: %w", message.Desc.FullName(), err)
	}
	queryStatistics, err := c.messageOptionBool(message, proprdbpb.E_QueryStatistics)
	if err != nil {
		return messageModel{}, fmt.Errorf("message %s query_statistics option: %w", message.Desc.FullName(), err)
	}
	projected := make([]projectedField, 0)
	signatures := make([]string, 0)
	fieldsByName := make(map[string]*protogen.Field)
	projectedByName := make(map[string]bool)
	projectedColumnsByPath := make(map[string]string)
	swiftProjectedByName := make(map[string]bool)

	for _, field := range message.Fields {
		fieldsByName[string(field.Desc.Name())] = field
	}

	for _, field := range message.Fields {
		external, err := c.fieldExternal(field)
		if err != nil {
			return messageModel{}, fmt.Errorf("field %s: %w", field.Desc.FullName(), err)
		}

		if !external {
			continue
		}

		projection, err := c.projectedFieldFromProto(field)
		if err != nil {
			return messageModel{}, fmt.Errorf("field %s: %w", field.Desc.FullName(), err)
		}

		switch strings.ToLower(projection.ColumnName) {
		case idColumn, atNSColumn, dataVariable:
			return messageModel{}, fmt.Errorf("field %s projects to reserved column %s", field.Desc.FullName(), projection.ColumnName)
		}
		normalizedColumnName := strings.ToLower(projection.ColumnName)
		if projectedByName[normalizedColumnName] {
			return messageModel{}, fmt.Errorf("field %s projects to duplicate column %s", field.Desc.FullName(), projection.ColumnName)
		}
		if swiftProjectedByName[projection.SwiftPropertyName] {
			return messageModel{}, fmt.Errorf("field %s projects to duplicate Swift property %s", field.Desc.FullName(), projection.SwiftPropertyName)
		}
		projected = append(projected, projection)
		projectedByName[normalizedColumnName] = true
		projectedColumnsByPath[projection.ProtoFieldName] = projection.ColumnName
		swiftProjectedByName[projection.SwiftPropertyName] = true
		signatures = append(signatures, projection.SchemaSignature)
	}

	paths, err := c.messageExternalPaths(message)
	if err != nil {
		return messageModel{}, err
	}
	for _, path := range paths {
		segments, err := c.resolveProjectionPath(message, path)
		if err != nil {
			return messageModel{}, fmt.Errorf("message %s external path %q: %w", message.Desc.FullName(), path, err)
		}
		projection, err := c.projectedFieldFromProto(segments[len(segments)-1])
		if err != nil {
			return messageModel{}, fmt.Errorf("external path %q: %w", path, err)
		}
		projection.Path = segments
		projection.ProtoFieldName = path
		projection.ColumnName = strings.ReplaceAll(path, ".", "_")
		projection.SwiftPropertyName = swiftFieldName(projection.ColumnName)
		if len(segments) > 1 {
			projection.LegacyOneofPresenceRepair = false
		}
		projection.IsOptional = len(segments) > 1 || projection.IsOptional
		projection.SchemaSignature = projection.ColumnName + ":" + segments[len(segments)-1].Desc.Kind().String()
		if projection.IsOptional {
			projection.SchemaSignature += projectionOptionalFlag
		}
		column := strings.ToLower(projection.ColumnName)
		if column == idColumn || column == atNSColumn || column == dataVariable {
			return messageModel{}, fmt.Errorf("external path %q projects to reserved column %s", path, column)
		}
		if projectedByName[column] || swiftProjectedByName[projection.SwiftPropertyName] {
			return messageModel{}, fmt.Errorf("external path %q projects to duplicate column %s", path, column)
		}
		projectedByName[column] = true
		projectedColumnsByPath[path] = projection.ColumnName
		swiftProjectedByName[projection.SwiftPropertyName] = true
		fieldsByName[path] = segments[len(segments)-1]
		projected = append(projected, projection)
		signature := projection.SchemaSignature
		if len(segments) > 1 {
			signature += ":path=" + path
		}
		signatures = append(signatures, signature)
	}

	hashFields, err := c.hashProjections(message)
	if err != nil {
		return messageModel{}, fmt.Errorf("message %s hash_projections: %w", message.Desc.FullName(), err)
	}
	hashColumns := map[string]string{}
	for _, field := range hashFields {
		column := strings.ToLower(field.ColumnName)
		if projectedByName[column] || swiftProjectedByName[field.SwiftPropertyName] {
			return messageModel{}, fmt.Errorf("hash projection column collision %s", column)
		}
		projectedByName[column] = true
		swiftProjectedByName[field.SwiftPropertyName] = true
		hashColumns[field.ProtoFieldName] = field.ColumnName
		projected = append(projected, field)
		signatures = append(signatures, field.SchemaSignature)
	}
	indexes, err := c.messageOptionIndexes(message, fieldsByName, projectedColumnsByPath)
	if err != nil {
		return messageModel{}, fmt.Errorf("message %s indexes option: %w", message.Desc.FullName(), err)
	}
	dirtyWindows, err := c.messageDirtyWindows(message, fieldsByName, projectedColumnsByPath)
	if err != nil {
		return messageModel{}, fmt.Errorf("message %s dirty_windows option: %w", message.Desc.FullName(), err)
	}
	dirtyKeys, err := c.messageDirtyKeys(message, projectedColumnsByPath, hashColumns)
	if err != nil {
		return messageModel{}, fmt.Errorf("message %s dirty_keys option: %w", message.Desc.FullName(), err)
	}
	return messageModel{
		GoName:              message.GoIdent.GoName,
		SwiftTypeName:       swiftMessageTypeNameForMessage(message),
		SwiftPropertyName:   swiftFieldName(string(message.Desc.Name())),
		TableName:           c.tableNameForMessage(message),
		TypeName:            string(message.Desc.FullName()),
		TableTypeName:       message.GoIdent.GoName + "Table",
		RowTypeName:         message.GoIdent.GoName + "Row",
		ProjectionSchema:    strings.Join(signatures, ";"),
		ProjectedFields:     projected,
		Indexes:             indexes,
		OmitSync:            omitSync,
		ValidateWrite:       validateWrite,
		AllowCustomIDInsert: allowCustomIDInsert,
		ChangeListeners:     changeListeners,
		QueryStatistics:     queryStatistics,
		DirtyWindows:        dirtyWindows,
		DirtyKeys:           dirtyKeys,
	}, nil
}

func (c modelCollector) messageDirtyKeys(message *protogen.Message, columns, hashes map[string]string) (trackers []messageDirtyKeys, err error) {
	options := message.Desc.Options()
	if !proto.HasExtension(options, proprdbpb.E_DirtyKeys) {
		return nil, nil
	}
	declarations, ok := proto.GetExtension(options, proprdbpb.E_DirtyKeys).([]*proprdbpb.DirtyKeys)
	if !ok {
		return nil, errors.New("invalid dirty_keys extension")
	}
	names := make(map[string]bool)
	for _, declaration := range declarations {
		if declaration == nil || !dirtyWindowNamePattern.MatchString(declaration.Name) {
			return nil, errors.New("dirty keys name must match [a-z][a-z0-9_]*")
		}
		if names[declaration.Name] {
			return nil, fmt.Errorf("duplicate dirty keys %s", declaration.Name)
		}
		names[declaration.Name] = true
		tracker := messageDirtyKeys{Name: declaration.Name}
		paths := make(map[string]bool)
		for _, path := range declaration.WatchedFields {
			if paths[path] {
				return nil, fmt.Errorf("duplicate watched field %q", path)
			}
			paths[path] = true
			column := columns[path]
			if column == "" {
				return nil, fmt.Errorf("dirty keys field %q must already be projected", path)
			}
			tracker.WatchedColumns = append(tracker.WatchedColumns, column)
		}
		watchedHashes := map[string]bool{}
		for _, name := range declaration.WatchedHashes {
			if watchedHashes[name] {
				return nil, fmt.Errorf("duplicate watched hash %q", name)
			}
			watchedHashes[name] = true
			column := hashes[name]
			if column == "" {
				return nil, fmt.Errorf("unknown watched hash %q", name)
			}
			tracker.WatchedColumns = append(tracker.WatchedColumns, column)
		}
		sort.Strings(tracker.WatchedColumns)
		trackers = append(trackers, tracker)
	}
	sort.Slice(trackers, func(i, j int) bool { return trackers[i].Name < trackers[j].Name })
	return trackers, nil
}

func (c modelCollector) messageDirtyWindows(message *protogen.Message, fields map[string]*protogen.Field, columns map[string]string) (windows []messageDirtyWindow, err error) {
	options := message.Desc.Options()
	if !proto.HasExtension(options, proprdbpb.E_DirtyWindows) {
		return nil, nil
	}
	declarations, ok := proto.GetExtension(options, proprdbpb.E_DirtyWindows).([]*proprdbpb.DirtyWindow)
	if !ok {
		return nil, errors.New("invalid dirty_windows extension")
	}
	names := make(map[string]bool)
	for _, declaration := range declarations {
		if declaration == nil || !dirtyWindowNamePattern.MatchString(declaration.Name) {
			return nil, errors.New("dirty window name must match [a-z][a-z0-9_]*")
		}
		if names[declaration.Name] {
			return nil, fmt.Errorf("duplicate dirty window %s", declaration.Name)
		}
		names[declaration.Name] = true
		end := declaration.EndField
		if end == "" {
			end = declaration.StartField
		}
		for _, path := range []string{declaration.StartField, end} {
			field, exists := fields[path]
			if !exists || columns[path] == "" {
				return nil, fmt.Errorf("dirty window field %q must already be projected", path)
			}
			switch field.Desc.Kind() {
			case protoreflect.Int32Kind, protoreflect.Int64Kind, protoreflect.Sint32Kind, protoreflect.Sint64Kind, protoreflect.Sfixed32Kind, protoreflect.Sfixed64Kind:
			default:
				return nil, fmt.Errorf("dirty window field %q must be a signed integer", path)
			}
		}
		windows = append(windows, messageDirtyWindow{Name: declaration.Name, StartColumn: columns[declaration.StartField], EndColumn: columns[end]})
	}
	sort.Slice(windows, func(i, j int) bool { return windows[i].Name < windows[j].Name })
	return windows, nil
}

func (c modelCollector) messageExternalPaths(message *protogen.Message) (paths []string, err error) {
	options := message.Desc.Options()
	if !proto.HasExtension(options, proprdbpb.E_ExternalPaths) {
		return nil, nil
	}
	paths, ok := proto.GetExtension(options, proprdbpb.E_ExternalPaths).([]string)
	if !ok {
		return nil, errors.New("invalid external_paths option")
	}
	paths = append([]string(nil), paths...)
	sort.Strings(paths)
	return paths, nil
}

func (c modelCollector) resolveProjectionPath(message *protogen.Message, path string) (fields []*protogen.Field, err error) {
	segments := strings.Split(path, ".")
	fields = make([]*protogen.Field, 0, len(segments))
	for index, name := range segments {
		var found *protogen.Field
		for _, field := range message.Fields {
			if string(field.Desc.Name()) == name {
				found = field
				break
			}
		}
		if found == nil {
			return nil, fmt.Errorf("unknown field %q", name)
		}
		if found.Desc.IsList() || found.Desc.IsMap() {
			return nil, errors.New("repeated and map fields cannot be projected")
		}
		fields = append(fields, found)
		if index < len(segments)-1 {
			if found.Message == nil {
				return nil, fmt.Errorf("intermediate field %q must be a message", name)
			}
			message = found.Message
		}
	}
	return fields, nil
}

func (c modelCollector) messageOptionIndexes(message *protogen.Message, fieldsByName map[string]*protogen.Field, projectedColumnsByPath map[string]string) ([]messageIndex, error) {
	messageOptions, ok := message.Desc.Options().(*descriptorpb.MessageOptions)
	if !ok || messageOptions == nil {
		return nil, nil
	}
	if !proto.HasExtension(messageOptions, proprdbpb.E_Indexes) {
		return nil, nil
	}

	value := proto.GetExtension(messageOptions, proprdbpb.E_Indexes)
	indexDefs, ok := value.([]*proprdbpb.Index)
	if !ok {
		return nil, fmt.Errorf("unexpected com.github.fingon.proprdb.indexes type %T", value)
	}

	indexes := make([]messageIndex, 0, len(indexDefs))
	signatureSeen := make(map[string]bool)
	nameSeen := make(map[string]bool)
	tableName := c.tableNameForMessage(message)
	for indexPosition, indexDef := range indexDefs {
		if indexDef == nil {
			return nil, fmt.Errorf("index %d is nil", indexPosition+1)
		}
		if len(indexDef.Fields) == 0 {
			return nil, fmt.Errorf("index %d must include at least one field", indexPosition+1)
		}
		columnNames := make([]string, 0, len(indexDef.Fields))
		columnSeen := make(map[string]bool)
		for fieldPosition, rawFieldName := range indexDef.Fields {
			fieldName := strings.TrimSpace(rawFieldName)
			if fieldName == "" {
				return nil, fmt.Errorf("index %d field %d is empty", indexPosition+1, fieldPosition+1)
			}
			if columnSeen[fieldName] {
				return nil, fmt.Errorf("index %d has duplicate field %q", indexPosition+1, fieldName)
			}
			columnName := fieldName
			if fieldName != atNSColumn && fieldName != idColumn {
				if _, ok := fieldsByName[fieldName]; !ok {
					return nil, fmt.Errorf("index %d references unknown field %q", indexPosition+1, fieldName)
				}
				var projected bool
				columnName, projected = projectedColumnsByPath[fieldName]
				if !projected {
					return nil, fmt.Errorf("index %d field %q must be marked (com.github.fingon.proprdb.external)=true or declared in external_paths", indexPosition+1, fieldName)
				}
			}
			columnSeen[fieldName] = true
			columnNames = append(columnNames, columnName)
		}
		signature := "idx:" + strings.Join(columnNames, ",")
		if signatureSeen[signature] {
			return nil, fmt.Errorf("duplicate index declaration for fields %q", strings.Join(columnNames, ","))
		}
		signatureSeen[signature] = true

		indexName := c.generatedIndexName(tableName, columnNames)
		if nameSeen[indexName] {
			return nil, fmt.Errorf("index name collision for generated name %q", indexName)
		}
		nameSeen[indexName] = true

		indexes = append(indexes, messageIndex{
			ColumnNames: columnNames,
			IndexName:   indexName,
			Signature:   signature,
		})
	}

	return indexes, nil
}

func (c modelCollector) messageOptionBool(message *protogen.Message, extension protoreflect.ExtensionType) (bool, error) {
	messageOptions, ok := message.Desc.Options().(*descriptorpb.MessageOptions)
	if !ok || messageOptions == nil {
		return false, nil
	}
	if !proto.HasExtension(messageOptions, extension) {
		return false, nil
	}
	value := proto.GetExtension(messageOptions, extension)
	switch enabled := value.(type) {
	case bool:
		return enabled, nil
	case *bool:
		if enabled == nil {
			return false, nil
		}
		return *enabled, nil
	default:
		return false, fmt.Errorf("unexpected option type %T", value)
	}
}

func (c modelCollector) fieldExternal(field *protogen.Field) (bool, error) {
	fieldOptions, ok := field.Desc.Options().(*descriptorpb.FieldOptions)
	if !ok || fieldOptions == nil {
		return false, nil
	}

	if !proto.HasExtension(fieldOptions, proprdbpb.E_External) {
		return false, nil
	}

	value := proto.GetExtension(fieldOptions, proprdbpb.E_External)

	switch external := value.(type) {
	case bool:
		return external, nil
	case *bool:
		if external == nil {
			return false, nil
		}

		return *external, nil
	default:
		return false, fmt.Errorf("unexpected com.github.fingon.proprdb.external type %T", value)
	}
}

func (c modelCollector) projectedFieldFromProto(field *protogen.Field) (projectedField, error) {
	if field.Desc.IsList() || field.Desc.IsMap() {
		return projectedField{}, errors.New("external field must be scalar")
	}

	columnName := string(field.Desc.Name())
	protoFieldName := string(field.Desc.Name())
	getterName := "Get" + field.GoName
	signature := fmt.Sprintf("%s:%s", columnName, field.Desc.Kind())
	isOptional := field.Desc.HasPresence()
	legacyOneofPresenceRepair := field.Desc.ContainingOneof() != nil && !field.Desc.HasOptionalKeyword()
	swiftOneofPropertyName := ""
	if legacyOneofPresenceRepair {
		swiftOneofPropertyName = swiftFieldName(string(field.Desc.ContainingOneof().Name()))
	}
	if isOptional {
		signature += projectionOptionalFlag
	}

	switch field.Desc.Kind() {
	case protoreflect.BoolKind:
		return projectedField{"", nil, columnName, protoFieldName, getterName, "INTEGER", "0", signature, isOptional, legacyOneofPresenceRepair, swiftFieldName(protoFieldName), swiftPresenceName(protoFieldName), swiftOneofPropertyName}, nil
	case protoreflect.Int32Kind,
		protoreflect.Sint32Kind,
		protoreflect.Sfixed32Kind,
		protoreflect.Int64Kind,
		protoreflect.Sint64Kind,
		protoreflect.Sfixed64Kind,
		protoreflect.Uint32Kind,
		protoreflect.Fixed32Kind,
		protoreflect.EnumKind:
		return projectedField{"", nil, columnName, protoFieldName, getterName, "INTEGER", "0", signature, isOptional, legacyOneofPresenceRepair, swiftFieldName(protoFieldName), swiftPresenceName(protoFieldName), swiftOneofPropertyName}, nil
	case protoreflect.Uint64Kind, protoreflect.Fixed64Kind:
		return projectedField{}, errors.New("uint64 and fixed64 fields cannot be projected")
	case protoreflect.FloatKind, protoreflect.DoubleKind:
		return projectedField{"", nil, columnName, protoFieldName, getterName, "REAL", "0", signature, isOptional, legacyOneofPresenceRepair, swiftFieldName(protoFieldName), swiftPresenceName(protoFieldName), swiftOneofPropertyName}, nil
	case protoreflect.StringKind:
		return projectedField{"", nil, columnName, protoFieldName, getterName, "TEXT", "''", signature, isOptional, legacyOneofPresenceRepair, swiftFieldName(protoFieldName), swiftPresenceName(protoFieldName), swiftOneofPropertyName}, nil
	case protoreflect.BytesKind:
		return projectedField{"", nil, columnName, protoFieldName, getterName, "BLOB", "X''", signature, isOptional, legacyOneofPresenceRepair, swiftFieldName(protoFieldName), swiftPresenceName(protoFieldName), swiftOneofPropertyName}, nil
	default:
		return projectedField{}, fmt.Errorf("unsupported external field kind %s", field.Desc.Kind())
	}
}

func (f projectedField) createColumnSQL() string {
	if f.IsOptional {
		return fmt.Sprintf(`"%s" %s`, f.ColumnName, f.SQLiteType)
	}
	return fmt.Sprintf(`"%s" %s NOT NULL DEFAULT %s`, f.ColumnName, f.SQLiteType, f.SQLiteDefault)
}

func (c modelCollector) tableNameForMessage(message *protogen.Message) string {
	fullName := strings.ReplaceAll(string(message.Desc.FullName()), ".", "_")
	return strings.ToLower(fullName)
}

func (c modelCollector) generatedIndexName(tableName string, columnNames []string) string {
	prefix := "idx_" + sanitizeSQLName(tableName) + "__"
	sanitizedColumns := make([]string, 0, len(columnNames))
	for _, columnName := range columnNames {
		sanitizedColumns = append(sanitizedColumns, sanitizeSQLName(columnName))
	}
	return prefix + strings.Join(sanitizedColumns, "_")
}

func sanitizeSQLName(value string) string {
	builder := strings.Builder{}
	lastUnderscore := false
	for _, character := range strings.ToLower(value) {
		isLower := character >= 'a' && character <= 'z'
		isDigit := character >= '0' && character <= '9'
		if isLower || isDigit {
			builder.WriteRune(character)
			lastUnderscore = false
			continue
		}
		if lastUnderscore {
			continue
		}
		builder.WriteByte('_')
		lastUnderscore = true
	}
	result := strings.Trim(builder.String(), "_")
	if result == "" {
		return "idx"
	}
	return result
}


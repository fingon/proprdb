const (
	swiftRuntimeModuleName = "ProprDBSwiftRuntime"
	swiftPublicVisibility  = "public"
)

type SwiftGeneratorOptions struct {
	Visibility           string
	PublicSynchronousAPI bool
}

type swiftEmitter struct {
	g               *protogen.GeneratedFile
	visibility      string
	actorVisibility string
}

// GenerateSwiftFile generates proprdb CRUD code for Swift.
func GenerateSwiftFile(plugin *protogen.Plugin, file *protogen.File, options SwiftGeneratorOptions) error {
	return GenerateSwiftFiles(plugin, []*protogen.File{file}, options)
}

func GenerateSwiftFiles(plugin *protogen.Plugin, files []*protogen.File, options SwiftGeneratorOptions) error {
	if len(files) == 0 {
		return nil
	}
	sort.Slice(files, func(left, right int) bool {
		return files[left].Desc.Path() < files[right].Desc.Path()
	})
	collector := modelCollector{}
	models := make([]messageModel, 0)
	modelFiles := make(map[string]*protogen.File)
	for _, file := range files {
		fileModels, err := collector.collectModels(file)
		if err != nil {
			return err
		}
		for _, model := range fileModels {
			modelFiles[model.TypeName] = file
		}
		models = append(models, fileModels...)
	}
	if len(models) == 0 {
		return nil
	}
	if err := validateModels(models); err != nil {
		return err
	}

	file := files[0]
	filename := file.GeneratedFilenamePrefix + ".proprdb.pb.swift"
	g := plugin.NewGeneratedFile(filename, "")
	g.P("// Code generated by protoc-gen-proprdb-swift. DO NOT EDIT.")
	g.P()
	g.P("import Foundation")
	g.P("import SwiftProtobuf")
	g.P("import ", swiftRuntimeModuleName)
	g.P()

	synchronousVisibility := ""
	if options.PublicSynchronousAPI {
		synchronousVisibility = swiftPublicVisibility
	}
	emitter := swiftEmitter{
		g:               g,
		visibility:      synchronousVisibility,
		actorVisibility: swiftVisibilityKeyword(options.Visibility),
	}
	for _, model := range models {
		emitter.emitModel(modelFiles[model.TypeName], model)
	}
	emitter.emitWrapper(modelFiles, models)
	return nil
}

func (e swiftEmitter) emitModel(file *protogen.File, model messageModel) {
	g := e.g
	swiftTypeName := model.SwiftTypeName
	tableNameConst := model.GoName + "TableName"
	typeNameConst := model.GoName + "TypeName"
	schemaConst := model.GoName + "ProjectionSchema"
	createTableConst := model.GoName + "CreateTableSQL"
	insertConst := model.GoName + "InsertSQL"
	upsertConst := model.GoName + "UpsertSQL"
	indexPrefixConst := model.GoName + "GeneratedIndexPrefix"
	visibility := e.visibilityPrefix()
	sharedVisibility := e.sharedVisibilityPrefix()

	g.P(visibility, "let ", tableNameConst, " = ", strconv.Quote(model.TableName))
	g.P("private let ", tableNameConst, "Quoted = quoteSQLiteIdentifier(", tableNameConst, ")")
	g.P(visibility, "let ", typeNameConst, " = ", strconv.Quote(model.TypeName))
	g.P(visibility, "let ", schemaConst, " = ", strconv.Quote(model.ProjectionSchema))
	g.P("private let ", createTableConst, " = ", strconv.Quote(model.createTableSQL()))
	g.P("private let ", insertConst, " = ", strconv.Quote(model.insertSQL(false)))
	g.P("private let ", upsertConst, " = ", strconv.Quote(model.insertSQL(true)))
	g.P("private let ", indexPrefixConst, " = ", strconv.Quote(model.generatedIndexPrefix()))
	for indexPosition, indexModel := range model.Indexes {
		g.P("private let ", model.GoName, "CreateIndexSQL", strconv.Itoa(indexPosition+1), " = ", strconv.Quote(model.createIndexSQL(indexModel)))
	}
	g.P()
	g.P("private let ", model.GoName, "GeneratedBinding = GeneratedTableBinding(")
	g.P("\tdescriptor: GeneratedTableDescriptor(tableName: ", tableNameConst, ", typeName: ", typeNameConst, ", isCore: false, syncEnabled: ", strconv.FormatBool(!model.OmitSync), ", changeListenersEnabled: ", strconv.FormatBool(model.ChangeListeners), ", queryStatisticsEnabled: ", strconv.FormatBool(model.QueryStatistics), "),")
	g.P("\tmessageType: ", swiftTypeName, ".self,")
	g.P("\tinsertSQL: ", insertConst, ",")
	g.P("\tupsertSQL: ", upsertConst, ",")
	g.P("\tcreateTableSQL: ", createTableConst, ",")
	g.P("\tprojectionSchema: ", schemaConst, ",")
	g.P("\tprojectedColumns: [")
	for _, projectedField := range model.ProjectedFields {
		protoKind := strings.TrimPrefix(strings.TrimSuffix(projectedField.SchemaSignature, projectionOptionalFlag), projectedField.ColumnName+":")
		g.P("\t\tProjectedColumnDescriptor(name: ", strconv.Quote(projectedField.ColumnName), ", protoKind: ", strconv.Quote(protoKind), ", sqliteType: ", strconv.Quote(projectedField.SQLiteType), ", defaultSQL: ", strconv.Quote(projectedField.SQLiteDefault), ", nullable: ", strconv.FormatBool(projectedField.IsOptional), ", legacyOneofPresenceRepair: ", strconv.FormatBool(projectedField.LegacyOneofPresenceRepair), "),")
	}
	g.P("\t],")
	g.P("\tgeneratedIndexes: [")
	for indexPosition, indexModel := range model.Indexes {
		g.P("\t\tGeneratedIndexDescriptor(name: ", strconv.Quote(indexModel.IndexName), ", createSQL: ", model.GoName, "CreateIndexSQL", strconv.Itoa(indexPosition+1), "),")
	}
	g.P("\t],")
	g.P("\tgeneratedIndexPrefix: ", indexPrefixConst, ",")
	g.P("\tdecodeAnyJSON: { try decodeAnyJSON($0, as: ", swiftTypeName, ".self) },")
	g.P("\tdecodeBinary: { try ", swiftTypeName, "(serializedBytes: $0) },")
	g.P("\tencodeAnyJSON: { message in")
	g.P("\t\tguard let data = message as? ", swiftTypeName, " else { throw ProprDBError(\"expected ", swiftTypeName, "\") }")
	g.P("\t\treturn try marshalAnyJSON(data, typeName: ", typeNameConst, ")")
	g.P("\t},")
	g.P("\tmessagesEqual: { left, right in")
	g.P("\t\tguard let left = left as? ", swiftTypeName, ", let right = right as? ", swiftTypeName, " else { return false }")
	g.P("\t\treturn left == right")
	g.P("\t},")
	g.P("\tprojectedValues: { message in")
	g.P("\t\tguard let data = message as? ", swiftTypeName, " else { throw ProprDBError(\"expected ", swiftTypeName, "\") }")
	g.P("\t\tvar values: [SQLiteBindValue] = []")
	for _, projectedField := range model.ProjectedFields {
		propertyName := projectedField.SwiftPropertyName
		if projectedField.IsOptional {
			if projectedField.LegacyOneofPresenceRepair {
				g.P("\t\tif case .", propertyName, " = data.", projectedField.SwiftOneofPropertyName, " { values.append(sqliteBindValue(data.", propertyName, ")) } else { values.append(.null) }")
			} else {
				g.P("\t\tif data.", projectedField.SwiftPresenceName, " { values.append(sqliteBindValue(data.", propertyName, ")) } else { values.append(.null) }")
			}
		} else {
			g.P("\t\tvalues.append(sqliteBindValue(data.", propertyName, "))")
		}
	}
	g.P("\t\treturn values")
	g.P("\t}")
	g.P(")")
	g.P()

	g.P(sharedVisibility, "struct ", model.RowTypeName, ": Equatable, Sendable {")
	g.P("\t", sharedVisibility, "var id: String")
	g.P("\t", sharedVisibility, "var atNs: Int64")
	g.P("\t", sharedVisibility, "var data: ", swiftTypeName)
	g.P("\t", sharedVisibility, "init(id: String, atNs: Int64, data: ", swiftTypeName, ") {")
	g.P("\t\tself.id = id")
	g.P("\t\tself.atNs = atNs")
	g.P("\t\tself.data = data")
	g.P("\t}")
	g.P("}")
	g.P()
	if model.ChangeListeners {
		g.P(sharedVisibility, "typealias ", model.GoName, "Change = TableChange<", swiftTypeName, ">")
		g.P()
	}

	g.P(visibility, "struct ", model.TableTypeName, " {")
	g.P("\tfileprivate let q: any DBTX")
	g.P("\t", visibility, "init(_ q: any DBTX) {")
	if model.ChangeListeners {
		g.P("\t\tself.q = withChangeListeners(q)")
	} else {
		g.P("\t\tself.q = q")
	}
	g.P("\t}")
	g.P()

	e.emitSwiftInitMethod(file, model, swiftTypeName, tableNameConst, typeNameConst, schemaConst, createTableConst, indexPrefixConst)
	e.emitSwiftSelectMethod(model, swiftTypeName, tableNameConst)
	e.emitSwiftInsertMethod(model, swiftTypeName, tableNameConst, insertConst)
	e.emitSwiftUpdateMethod(model, swiftTypeName, tableNameConst, upsertConst)
	e.emitSwiftDeleteMethod(model)
	e.emitSwiftApplyWithAtNsMethods(model, swiftTypeName, tableNameConst, upsertConst)
	e.emitSwiftDrainUnknownMethod(file, model, swiftTypeName, typeNameConst)
	if model.ChangeListeners {
		g.P("\t", visibility, "func changes() -> AsyncStream<", model.GoName, "Change> {")
		g.P("\t\ttableChanges(q, tableName: ", tableNameConst, ", as: ", swiftTypeName, ".self)")
		g.P("\t}")
		g.P()
	}
	g.P("}")
	g.P()
}

func (e swiftEmitter) emitSwiftInitMethod(file *protogen.File, model messageModel, swiftTypeName, _, typeNameConst, schemaConst, createTableConst, indexPrefixConst string) {
	g := e.g
	g.P("\t", e.visibilityPrefix(), "func initialize() throws {")
	g.P("\t\ttry ensureCoreTables(q)")
	g.P("\t\ttry auditObjectIDs(q, bindings: [", model.GoName, "GeneratedBinding])")
	g.P("\t\ttry reconcileGeneratedTable(q, binding: ", model.GoName, "GeneratedBinding)")
	g.P("\t\ttry drainUnknownRows(", typeNameConst, ")")
	g.P("\t}")
	g.P()
	_ = swiftTypeName
	_ = file
	_ = schemaConst
	_ = createTableConst
	_ = indexPrefixConst
}

func (e swiftEmitter) emitSwiftSelectMethod(model messageModel, swiftTypeName, tableNameConst string) {
	g := e.g
	g.P("\t", e.visibilityPrefix(), "func select(where whereClause: String = \"\", arguments: [SQLiteBindValue] = []) throws -> [", model.RowTypeName, "] {")
	g.P("\t\tvar query = \"SELECT id, at_ns, data FROM \" + ", tableNameConst, "Quoted")
	g.P("\t\tif !whereClause.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {")
	g.P("\t\t\tquery += \" WHERE \" + whereClause")
	g.P("\t\t}")
	if model.QueryStatistics {
		g.P("\t\treturn try measureQuery(q, tableName: ", tableNameConst, ", query: query) {")
	}
	g.P("\t\treturn try q.withRows(query, bindValues: arguments) { rows in")
	g.P("\t\t\tvar result: [", model.RowTypeName, "] = []")
	g.P("\t\t\twhile let row = try rows.next() {")
	g.P("\t\t\t\tlet id = try row.string(at: 0)")
	g.P("\t\t\t\tlet atNs = try row.int64(at: 1)")
	g.P("\t\t\t\tlet dataBytes = try row.data(at: 2)")
	g.P("\t\t\t\tlet data = try ", swiftTypeName, "(serializedBytes: dataBytes)")
	g.P("\t\t\t\tresult.append(", model.RowTypeName, "(id: id, atNs: atNs, data: data))")
	g.P("\t\t\t}")
	g.P("\t\t\treturn result")
	g.P("\t\t}")
	if model.QueryStatistics {
		g.P("\t\t}")
	}
	g.P("\t}")
	g.P()
}

func (e swiftEmitter) emitSwiftInsertMethod(model messageModel, swiftTypeName, _, _ string) {
	g := e.g
	g.P("\t", e.visibilityPrefix(), "func insert(_ data: ", swiftTypeName, ") throws -> ", model.RowTypeName, " {")
	g.P("\t\tlet id = try uuidV7()")
	g.P("\t\ttry validateUUIDV7(id)")
	g.P("\t\treturn try insertWithIDInternal(id: id, data: data)")
	g.P("\t}")
	g.P()
	if model.AllowCustomIDInsert {
		g.P("\t", e.visibilityPrefix(), "func insertWithID(_ id: String, data: ", swiftTypeName, ") throws -> ", model.RowTypeName, " {")
		g.P("\t\treturn try insertWithIDInternal(id: id, data: data)")
		g.P("\t}")
		g.P()
	}
	g.P("\tprivate func insertWithIDInternal(id: String, data: ", swiftTypeName, ") throws -> ", model.RowTypeName, " {")
	g.P("\t\tif id.isEmpty {")
	g.P("\t\t\tthrow ProprDBError(\"empty id\")")
	g.P("\t\t}")
	g.P("\t\ttry validateUUIDV7(id)")
	if model.ValidateWrite {
		g.P("\t\ttry validateForWrite(data)")
	}
	g.P("\t\tlet atNs = try writeLocalObject(q, binding: ", model.GoName, "GeneratedBinding, id: id, message: data, insert: true)")
	g.P("\t\treturn ", model.RowTypeName, "(id: id, atNs: atNs, data: data)")
	g.P("\t}")
	g.P()
}


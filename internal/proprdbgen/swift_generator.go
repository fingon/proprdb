const swiftRuntimeModuleName = "ProprDBSwiftRuntime"

type swiftEmitter struct {
	g *protogen.GeneratedFile
}

// GenerateSwiftFile generates proprdb CRUD code for Swift.
func GenerateSwiftFile(plugin *protogen.Plugin, file *protogen.File) error {
	collector := modelCollector{}
	models, err := collector.collectModels(file)
	if err != nil {
		return err
	}
	if len(models) == 0 {
		return nil
	}

	filename := file.GeneratedFilenamePrefix + ".proprdb.pb.swift"
	g := plugin.NewGeneratedFile(filename, "")
	g.P("// Code generated by protoc-gen-proprdb-swift. DO NOT EDIT.")
	g.P()
	g.P("import Foundation")
	g.P("import SwiftProtobuf")
	g.P("import ", swiftRuntimeModuleName)
	g.P()

	emitter := swiftEmitter{g: g}
	for _, model := range models {
		emitter.emitModel(file, model)
	}
	emitter.emitWrapper(file, models)
	return nil
}

func (e swiftEmitter) emitModel(file *protogen.File, model messageModel) {
	g := e.g
	swiftTypeName := swiftMessageTypeName(file, model.GoName)
	tableNameConst := model.GoName + "TableName"
	typeNameConst := model.GoName + "TypeName"
	schemaConst := model.GoName + "ProjectionSchema"
	createTableConst := model.GoName + "CreateTableSQL"
	insertConst := model.GoName + "InsertSQL"
	upsertConst := model.GoName + "UpsertSQL"
	reprojectConst := model.GoName + "ReprojectSQL"
	indexPrefixConst := model.GoName + "GeneratedIndexPrefix"

	g.P("let ", tableNameConst, " = ", strconv.Quote(model.TableName))
	g.P("private let ", tableNameConst, "Quoted = quoteSQLiteIdentifier(", tableNameConst, ")")
	g.P("let ", typeNameConst, " = ", strconv.Quote(model.TypeName))
	g.P("let ", schemaConst, " = ", strconv.Quote(model.ProjectionSchema))
	g.P("private let ", createTableConst, " = ", strconv.Quote(model.createTableSQL()))
	g.P("private let ", insertConst, " = ", strconv.Quote(model.insertSQL(false)))
	g.P("private let ", upsertConst, " = ", strconv.Quote(model.insertSQL(true)))
	g.P("private let ", indexPrefixConst, " = ", strconv.Quote(model.generatedIndexPrefix()))
	for indexPosition, indexModel := range model.Indexes {
		g.P("private let ", model.GoName, "CreateIndexSQL", strconv.Itoa(indexPosition+1), " = ", strconv.Quote(model.createIndexSQL(indexModel)))
	}
	if len(model.ProjectedFields) > 0 {
		g.P("private let ", reprojectConst, " = ", strconv.Quote(model.reprojectSQL()))
	}
	g.P()

	g.P("struct ", model.RowTypeName, ": Equatable {")
	g.P("\tvar id: String")
	g.P("\tvar atNs: Int64")
	g.P("\tvar data: ", swiftTypeName)
	g.P("\tinit(id: String, atNs: Int64, data: ", swiftTypeName, ") {")
	g.P("\t\tself.id = id")
	g.P("\t\tself.atNs = atNs")
	g.P("\t\tself.data = data")
	g.P("\t}")
	g.P("}")
	g.P()

	g.P("struct ", model.TableTypeName, " {")
	g.P("\tfileprivate let q: any DBTX")
	g.P("\tinit(_ q: any DBTX) {")
	g.P("\t\tself.q = q")
	g.P("\t}")
	g.P()

	e.emitSwiftInitMethod(file, model, swiftTypeName, tableNameConst, typeNameConst, schemaConst, createTableConst, indexPrefixConst)
	e.emitSwiftSelectMethod(model, swiftTypeName, tableNameConst)
	e.emitSwiftInsertMethod(model, swiftTypeName, tableNameConst, insertConst)
	e.emitSwiftUpdateMethod(model, swiftTypeName, tableNameConst, upsertConst)
	e.emitSwiftDeleteMethod(model, tableNameConst)
	e.emitSwiftApplyWithAtNsMethods(model, swiftTypeName, tableNameConst, upsertConst)
	if len(model.ProjectedFields) > 0 {
		e.emitSwiftReprojectMethod(file, model, swiftTypeName, tableNameConst, reprojectConst)
	}
	e.emitSwiftDrainUnknownMethod(file, swiftTypeName, typeNameConst)
	g.P("}")
	g.P()
}

func (e swiftEmitter) emitSwiftInitMethod(file *protogen.File, model messageModel, swiftTypeName, tableNameConst, typeNameConst, schemaConst, createTableConst, indexPrefixConst string) {
	g := e.g
	g.P("\tfunc initialize() throws {")
	g.P("\t\ttry ensureCoreTables(q)")
	g.P("\t\ttry q.execute(", createTableConst, ")")
	if len(model.ProjectedFields) > 0 {
		g.P("\t\tlet existingColumns = try q.withRows(\"PRAGMA table_info(\\\"\\(", tableNameConst, ")\\\")\") { rows in")
		g.P("\t\t\tvar columns = Set<String>()")
		g.P("\t\t\twhile let row = try rows.next() {")
		g.P("\t\t\t\tcolumns.insert(try row.string(at: 1))")
		g.P("\t\t\t}")
		g.P("\t\t\treturn columns")
		g.P("\t\t}")
		for _, projectedField := range model.ProjectedFields {
			g.P("\t\tif !existingColumns.contains(", strconv.Quote(projectedField.ColumnName), ") {")
			g.P("\t\t\ttry q.execute(\"ALTER TABLE \" + ", tableNameConst, "Quoted + \" ADD COLUMN ", escapeSwiftStringLiteralContent(projectedField.createColumnSQL()), "\")")
			g.P("\t\t}")
		}
	}

	g.P("\t\ttry ensureManagedIndexes(q, tableName: ", tableNameConst, ", generatedIndexPrefix: ", indexPrefixConst, ", createIndexSQL: [")
	for indexPosition := range model.Indexes {
		g.P("\t\t\t", model.GoName, "CreateIndexSQL", strconv.Itoa(indexPosition+1), ",")
	}
	g.P("\t\t], desiredIndexNames: [")
	for _, indexModel := range model.Indexes {
		g.P("\t\t\t", strconv.Quote(indexModel.IndexName), ",")
	}
	g.P("\t\t])")

	g.P("\t\tlet currentSchema = try q.withRows(\"SELECT schema_hash FROM \\(_proprdbSchemaTableName) WHERE table_name = ?\", arguments: [", tableNameConst, "]) { rows -> String? in")
	g.P("\t\t\tif let row = try rows.next() {")
	g.P("\t\t\t\treturn try row.string(at: 0)")
	g.P("\t\t\t}")
	g.P("\t\t\treturn nil as String?")
	g.P("\t\t}")
	g.P("\t\tif let currentSchema, currentSchema != ", schemaConst, " {")
	if len(model.ProjectedFields) > 0 {
		g.P("\t\t\ttry reproject()")
	}
	g.P("\t\t\ttry q.execute(\"UPDATE \\(_proprdbSchemaTableName) SET schema_hash = ? WHERE table_name = ?\", arguments: [", schemaConst, ", ", tableNameConst, "])")
	g.P("\t\t} else if currentSchema == nil {")
	g.P("\t\t\ttry q.execute(\"INSERT INTO \\(_proprdbSchemaTableName) (table_name, schema_hash) VALUES (?, ?)\", arguments: [", tableNameConst, ", ", schemaConst, "])")
	g.P("\t\t}")
	g.P("\t\ttry drainUnknownRows(", typeNameConst, ")")
	g.P("\t}")
	g.P()
	_ = swiftTypeName
	_ = file
}

func (e swiftEmitter) emitSwiftSelectMethod(model messageModel, swiftTypeName, tableNameConst string) {
	g := e.g
	g.P("\tfunc select(where whereClause: String = \"\", arguments: [Any?] = []) throws -> [", model.RowTypeName, "] {")
	g.P("\t\tvar query = \"SELECT id, at_ns, data FROM \" + ", tableNameConst, "Quoted")
	g.P("\t\tif !whereClause.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {")
	g.P("\t\t\tquery += \" WHERE \" + whereClause")
	g.P("\t\t}")
	g.P("\t\treturn try q.withRows(query, arguments: arguments) { rows in")
	g.P("\t\t\tvar result: [", model.RowTypeName, "] = []")
	g.P("\t\t\twhile let row = try rows.next() {")
	g.P("\t\t\t\tlet id = try row.string(at: 0)")
	g.P("\t\t\t\tlet atNs = try row.int64(at: 1)")
	g.P("\t\t\t\tlet dataBytes = try row.data(at: 2)")
	g.P("\t\t\t\tlet data = try ", swiftTypeName, "(serializedBytes: dataBytes)")
	g.P("\t\t\t\tresult.append(", model.RowTypeName, "(id: id, atNs: atNs, data: data))")
	g.P("\t\t\t}")
	g.P("\t\t\treturn result")
	g.P("\t\t}")
	g.P("\t}")
	g.P()
}

func (e swiftEmitter) emitSwiftInsertMethod(model messageModel, swiftTypeName, tableNameConst, insertConst string) {
	g := e.g
	g.P("\tfunc insert(_ data: ", swiftTypeName, ") throws -> ", model.RowTypeName, " {")
	g.P("\t\tlet id = try uuidV7()")
	g.P("\t\ttry validateUUID(id)")
	g.P("\t\treturn try insertWithIDInternal(id: id, data: data)")
	g.P("\t}")
	g.P()
	if model.AllowCustomIDInsert {
		g.P("\tfunc insertWithID(_ id: String, data: ", swiftTypeName, ") throws -> ", model.RowTypeName, " {")
		g.P("\t\treturn try insertWithIDInternal(id: id, data: data)")
		g.P("\t}")
		g.P()
	}
	g.P("\tprivate func insertWithIDInternal(id: String, data: ", swiftTypeName, ") throws -> ", model.RowTypeName, " {")
	g.P("\t\tif id.isEmpty {")
	g.P("\t\t\tthrow ProprDBError(\"empty id\")")
	g.P("\t\t}")
	g.P("\t\ttry validateUUID(id)")
	if model.ValidateWrite {
		g.P("\t\ttry validateForWrite(data)")
	}
	g.P("\t\tlet atNs = nowNs()")
	g.P("\t\tlet dataBytes = try data.serializedData()")
	g.P("\t\ttry q.execute(\"DELETE FROM \\(_deletedTableName) WHERE table_name = ? AND id = ?\", arguments: [", tableNameConst, ", id])")
	g.P("\t\tvar insertArguments: [Any?] = [id, atNs, dataBytes]")
	for _, projectedField := range model.ProjectedFields {
		e.emitSwiftProjectedFieldAppend("insertArguments", "data", projectedField, "\t\t")
	}
	g.P("\t\ttry q.execute(", insertConst, ", arguments: insertArguments)")
	g.P("\t\treturn ", model.RowTypeName, "(id: id, atNs: atNs, data: data)")
	g.P("\t}")
	g.P()
}


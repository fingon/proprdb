func (e swiftEmitter) emitSwiftApplyWithAtNsMethods(model messageModel, swiftTypeName, _, _ string) {
	g := e.g
	g.P("\tfileprivate func upsertWithAtNs(id: String, atNs: Int64, data: ", swiftTypeName, ") throws {")
	g.P("\t\tif id.isEmpty {")
	g.P("\t\t\tthrow ProprDBError(\"empty id\")")
	g.P("\t\t}")
	g.P("\t\tlet dataJSON = try marshalAnyJSON(data, typeName: ", model.GoName, "TypeName)")
	g.P("\t\ttry applyIncomingObject(q, binding: ", model.GoName, "GeneratedBinding, record: JSONLRecord(id: id, deleted: false, atNs: atNs, data: dataJSON))")
	g.P("\t}")
	g.P()
	g.P("\tfileprivate func tombstoneWithAtNs(id: String, atNs: Int64) throws {")
	g.P("\t\tif id.isEmpty {")
	g.P("\t\t\tthrow ProprDBError(\"empty id\")")
	g.P("\t\t}")
	g.P("\t\tlet dataJSON = try marshalTypeOnlyAnyJSON(typeName: ", model.GoName, "TypeName)")
	g.P("\t\ttry applyIncomingObject(q, binding: ", model.GoName, "GeneratedBinding, record: JSONLRecord(id: id, deleted: true, atNs: atNs, data: dataJSON))")
	g.P("\t}")
	g.P()
}

func (e swiftEmitter) emitSwiftDrainUnknownMethod(file *protogen.File, model messageModel, _, typeNameConst string) {
	g := e.g
	g.P("\tfileprivate func drainUnknownRows(_ typeName: String) throws {")
	g.P("\t\tguard typeName == ", typeNameConst, " else { throw ProprDBError(\"unexpected type name \\(typeName)\") }")
	g.P("\t\ttry drainBoundUnknown(q, bindings: [", model.GoName, "GeneratedBinding])")
	g.P("\t}")
	g.P()
	g.P("\t", e.visibilityPrefix(), "func drainUnknownRows() throws {")
	g.P("\t\ttry drainUnknownRows(", typeNameConst, ")")
	g.P("\t}")
	g.P()
	_ = file
}

func (e swiftEmitter) emitWrapper(_ map[string]*protogen.File, models []messageModel) {
	g := e.g
	visibility := e.visibilityPrefix()
	actorVisibility := e.actorVisibilityPrefix()
	g.P("private let crudGeneratedBindings = [")
	for _, model := range models {
		g.P("\t", model.GoName, "GeneratedBinding,")
	}
	g.P("]")
	g.P()
	g.P(visibility, "struct CRUD {")
	for _, model := range models {
		g.P("\t", visibility, "let ", model.SwiftPropertyName, ": ", model.TableTypeName)
	}
	g.P("\t", visibility, "init(_ q: any DBTX) {")
	if modelsHaveChangeListeners(models) {
		g.P("\t\tlet tracked = withChangeListeners(q)")
	}
	for _, model := range models {
		constructorQ := "q"
		if modelsHaveChangeListeners(models) {
			constructorQ = "tracked"
		}
		g.P("\t\tself.", model.SwiftPropertyName, " = ", model.TableTypeName, "(", constructorQ, ")")
	}
	g.P("\t}")
	g.P("\tprivate func dbtx() -> any DBTX { ", models[0].SwiftPropertyName, ".q }")
	g.P("\t", visibility, "func tableDescriptors() -> [GeneratedTableDescriptor] { crudGeneratedBindings.map(\\.descriptor) + coreTableDescriptors() }")
	g.P("\t", visibility, "func initialize() throws {")
	for _, model := range models {
		g.P("\t\ttry ", model.SwiftPropertyName, ".initialize()")
	}
	g.P("\t}")
	g.P("\t", visibility, "func prepareJSONL(remote: String) throws -> PreparedJSONLExport { try prepareBoundJSONL(dbtx(), bindings: crudGeneratedBindings, remote: remote) }")
	g.P("\t", visibility, "func acknowledgeJSONL(_ checkpoint: JSONLCheckpoint) throws { try acknowledgeBoundJSONL(dbtx(), checkpoint: checkpoint) }")
	g.P("\t", visibility, "func discardJSONL(_ checkpoint: JSONLCheckpoint) throws { try discardBoundJSONL(dbtx(), checkpoint: checkpoint) }")
	g.P("\t", visibility, "func writeJSONL(remote: String) throws -> String {")
	g.P("\t\tlet prepared = try prepareJSONL(remote: remote)")
	g.P("\t\ttry acknowledgeJSONL(prepared.checkpoint)")
	g.P("\t\treturn prepared.text")
	g.P("\t}")
	g.P("\t", visibility, "func readJSONL(remote: String, stream: InputStream) throws { try readBoundJSONL(dbtx(), bindings: crudGeneratedBindings, remote: remote, stream: stream) }")
	g.P("}")
	g.P()
	for _, model := range models {
		propertyName := model.SwiftPropertyName
		swiftTypeName := model.SwiftTypeName
		proxyName := model.GoName + "TableProxy"
		g.P(actorVisibility, "struct ", proxyName, ": Sendable {")
		g.P("\tfileprivate let actor: ProprDBActor")
		g.P()
		g.P("\t", actorVisibility, "func initialize() async throws { try await actor._", propertyName, "Initialize() }")
		g.P("\t", actorVisibility, "func select(where whereClause: String = \"\", arguments: [SQLiteBindValue] = []) async throws -> [", model.RowTypeName, "] { try await actor._", propertyName, "Select(where: whereClause, arguments: arguments) }")
		g.P("\t", actorVisibility, "func insert(_ data: ", swiftTypeName, ") async throws -> ", model.RowTypeName, " { try await actor._", propertyName, "Insert(data) }")
		if model.AllowCustomIDInsert {
			g.P("\t", actorVisibility, "func insertWithID(_ id: String, data: ", swiftTypeName, ") async throws -> ", model.RowTypeName, " { try await actor._", propertyName, "InsertWithID(id, data: data) }")
		}
		g.P("\t", actorVisibility, "func updateByID(_ id: String, data: ", swiftTypeName, ") async throws -> ", model.RowTypeName, " { try await actor._", propertyName, "UpdateByID(id, data: data) }")
		g.P("\t", actorVisibility, "func updateRow(_ row: ", model.RowTypeName, ") async throws -> ", model.RowTypeName, " { try await actor._", propertyName, "UpdateRow(row) }")
		g.P("\t", actorVisibility, "func deleteByID(_ id: String) async throws { try await actor._", propertyName, "DeleteByID(id) }")
		g.P("\t", actorVisibility, "func deleteRow(_ row: ", model.RowTypeName, ") async throws { try await actor._", propertyName, "DeleteRow(row) }")
		g.P("\t", actorVisibility, "func drainUnknownRows() async throws { try await actor._", propertyName, "DrainUnknownRows() }")
		if model.ChangeListeners {
			g.P("\t", actorVisibility, "func changes() async throws -> AsyncStream<", model.GoName, "Change> { try await actor._", propertyName, "Changes() }")
		}
		g.P("}")
		g.P()
	}
	g.P("extension ProprDBActor {")
	g.P("\t", actorVisibility, "func initialize() throws { try withDatabase { try CRUD($0).initialize() } }")
	g.P("\t", actorVisibility, "func tableDescriptors() throws -> [GeneratedTableDescriptor] { try withDatabase { CRUD($0).tableDescriptors() } }")
	for _, model := range models {
		propertyName := model.SwiftPropertyName
		swiftTypeName := model.SwiftTypeName
		proxyName := model.GoName + "TableProxy"
		g.P("\t", actorVisibility, "nonisolated var ", propertyName, ": ", proxyName, " { ", proxyName, "(actor: self) }")
		g.P("\tfileprivate func _", propertyName, "Initialize() throws { try withDatabase { try CRUD($0).", propertyName, ".initialize() } }")
		g.P("\tfileprivate func _", propertyName, "Select(where whereClause: String, arguments: [SQLiteBindValue]) throws -> [", model.RowTypeName, "] { try withDatabase { try CRUD($0).", propertyName, ".select(where: whereClause, arguments: arguments) } }")
		g.P("\tfileprivate func _", propertyName, "Insert(_ data: ", swiftTypeName, ") throws -> ", model.RowTypeName, " { try withDatabase { try CRUD($0).", propertyName, ".insert(data) } }")
		if model.AllowCustomIDInsert {
			g.P("\tfileprivate func _", propertyName, "InsertWithID(_ id: String, data: ", swiftTypeName, ") throws -> ", model.RowTypeName, " { try withDatabase { try CRUD($0).", propertyName, ".insertWithID(id, data: data) } }")
		}
		g.P("\tfileprivate func _", propertyName, "UpdateByID(_ id: String, data: ", swiftTypeName, ") throws -> ", model.RowTypeName, " { try withDatabase { try CRUD($0).", propertyName, ".updateByID(id, data: data) } }")
		g.P("\tfileprivate func _", propertyName, "UpdateRow(_ row: ", model.RowTypeName, ") throws -> ", model.RowTypeName, " { try withDatabase { try CRUD($0).", propertyName, ".updateRow(row) } }")
		g.P("\tfileprivate func _", propertyName, "DeleteByID(_ id: String) throws { try withDatabase { try CRUD($0).", propertyName, ".deleteByID(id) } }")
		g.P("\tfileprivate func _", propertyName, "DeleteRow(_ row: ", model.RowTypeName, ") throws { try withDatabase { try CRUD($0).", propertyName, ".deleteRow(row) } }")
		g.P("\tfileprivate func _", propertyName, "DrainUnknownRows() throws { try withDatabase { try CRUD($0).", propertyName, ".drainUnknownRows() } }")
		if model.ChangeListeners {
			g.P("\tfileprivate func _", propertyName, "Changes() throws -> AsyncStream<", model.GoName, "Change> { try withDatabase { CRUD($0).", propertyName, ".changes() } }")
		}
	}
	g.P("\t", actorVisibility, "func prepareJSONL(remote: String) throws -> PreparedJSONLExport { try withDatabase { try CRUD($0).prepareJSONL(remote: remote) } }")
	g.P("\t", actorVisibility, "func acknowledgeJSONL(_ checkpoint: JSONLCheckpoint) throws { try withDatabase { try CRUD($0).acknowledgeJSONL(checkpoint) } }")
	g.P("\t", actorVisibility, "func discardJSONL(_ checkpoint: JSONLCheckpoint) throws { try withDatabase { try CRUD($0).discardJSONL(checkpoint) } }")
	g.P("\t", actorVisibility, "func writeJSONL(remote: String) throws -> String { try withDatabase { try CRUD($0).writeJSONL(remote: remote) } }")
	g.P("\t", actorVisibility, "func readJSONL(remote: String, stream: InputStream) throws { try withDatabase { try CRUD($0).readJSONL(remote: remote, stream: stream) } }")
	g.P("}")
}

func swiftMessageTypeNameForMessage(message *protogen.Message) string {
	names := []string{swiftSanitizeTypeName(string(message.Desc.Name()))}
	for parent := message.Desc.Parent(); ; parent = parent.Parent() {
		parentMessage, ok := parent.(protoreflect.MessageDescriptor)
		if !ok {
			break
		}
		names = append([]string{swiftSanitizeTypeName(string(parentMessage.Name()))}, names...)
	}
	prefix := swiftFileTypePrefix(message.Desc.ParentFile())
	names[0] = prefix + names[0]
	return strings.Join(names, ".")
}

func swiftFileTypePrefix(file protoreflect.FileDescriptor) string {
	options, ok := file.Options().(*descriptorpb.FileOptions)
	if ok && options.SwiftPrefix != nil {
		return options.GetSwiftPrefix()
	}
	packageName := string(file.Package())
	if packageName == "" {
		return ""
	}
	var result strings.Builder
	uppercaseNext := true
	for _, character := range packageName {
		switch character {
		case '_':
			uppercaseNext = true
		case '.':
			result.WriteRune('_')
			uppercaseNext = true
		default:
			if uppercaseNext {
				result.WriteString(strings.ToUpper(string(character)))
				uppercaseNext = false
			} else {
				result.WriteRune(character)
			}
		}
	}
	result.WriteRune('_')
	return result.String()
}

func swiftFieldName(protoName string) string {
	name := swiftLowerCamelCase(protoName)
	if swiftReservedFieldNames[name] {
		return name + "_p"
	}
	if swiftKeywords[name] {
		return "`" + name + "`"
	}
	return name
}

func swiftPresenceName(protoName string) string {
	baseName := swiftLowerCamelCase(protoName)
	name := "has" + swiftUpperCamelCase(protoName)
	if swiftReservedFieldNames[baseName] || hasUppercasePrefix(baseName, "has") || hasUppercasePrefix(baseName, "clear") {
		return name + "_p"
	}
	return name
}

func swiftLowerCamelCase(value string) string {
	upper := swiftUpperCamelCase(value)
	if upper == "" {
		return ""
	}
	for _, abbreviation := range []string{"HTTPS", "HTTP", "URL", "ID"} {
		if strings.HasPrefix(upper, abbreviation) {
			return strings.ToLower(abbreviation) + upper[len(abbreviation):]
		}
	}
	return strings.ToLower(upper[:1]) + upper[1:]
}

func swiftUpperCamelCase(value string) string {
	parts := strings.FieldsFunc(value, func(character rune) bool { return character == '_' })
	var result strings.Builder
	for _, part := range parts {
		lower := strings.ToLower(part)
		switch lower {
		case "id", "url", "http", "https":
			result.WriteString(strings.ToUpper(lower))
		default:
			if lower != "" {
				result.WriteString(strings.ToUpper(lower[:1]))
				result.WriteString(lower[1:])
			}
		}
	}
	return result.String()
}

func swiftSanitizeTypeName(value string) string {
	if swiftReservedTypeNames[value] || strings.HasSuffix(value, "Message") {
		return value + "Message"
	}
	return value
}

func hasUppercasePrefix(value, prefix string) bool {
	if !strings.HasPrefix(value, prefix) || len(value) == len(prefix) {
		return false
	}
	next := value[len(prefix)]
	return next >= 'A' && next <= 'Z'
}


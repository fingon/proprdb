func (e swiftEmitter) emitSwiftReprojectMethod(file *protogen.File, model messageModel, swiftTypeName, tableNameConst, reprojectConst string) {
	g := e.g
	g.P("\tprivate func reproject() throws {")
	g.P("\t\tlet rowsToReproject = try q.withRows(\"SELECT id, data FROM \" + ", tableNameConst, "Quoted) { rows in")
	g.P("\t\t\tvar buffered: [(String, Data)] = []")
	g.P("\t\t\twhile let row = try rows.next() {")
	g.P("\t\t\t\tbuffered.append((try row.string(at: 0), try row.data(at: 1)))")
	g.P("\t\t\t}")
	g.P("\t\t\treturn buffered")
	g.P("\t\t}")
	g.P("\t\tfor (id, dataBytes) in rowsToReproject {")
	g.P("\t\t\tlet data = try ", swiftTypeName, "(serializedBytes: dataBytes)")
	g.P("\t\t\tvar reprojectArguments: [Any?] = []")
	for _, projectedField := range model.ProjectedFields {
		e.emitSwiftProjectedFieldAppend("reprojectArguments", "data", projectedField, "\t\t\t")
	}
	g.P("\t\t\treprojectArguments.append(id)")
	g.P("\t\t\ttry q.execute(", reprojectConst, ", arguments: reprojectArguments)")
	g.P("\t\t}")
	g.P("\t}")
	g.P()
	_ = file
}

func (e swiftEmitter) emitSwiftDrainUnknownMethod(file *protogen.File, swiftTypeName, typeNameConst string) {
	g := e.g
	g.P("\tfileprivate func drainUnknownRows(_ typeName: String) throws {")
	g.P("\t\ttry replayUnknownByType(q, typeName: typeName) { record in")
	g.P("\t\t\tif record.deleted {")
	g.P("\t\t\t\ttry tombstoneWithAtNs(id: record.id, atNs: record.atNs)")
	g.P("\t\t\t\treturn")
	g.P("\t\t\t}")
	g.P("\t\t\tlet data = try decodeAnyJSON(record.data, as: ", swiftTypeName, ".self)")
	g.P("\t\t\ttry upsertWithAtNs(id: record.id, atNs: record.atNs, data: data)")
	g.P("\t\t}")
	g.P("\t}")
	g.P()
	g.P("\tfunc drainUnknownRows() throws {")
	g.P("\t\ttry drainUnknownRows(", typeNameConst, ")")
	g.P("\t}")
	g.P()
	_ = file
}

func (e swiftEmitter) emitSwiftProjectedFieldAppend(argumentsName, dataName string, projectedField projectedField, indent string) {
	g := e.g
	propertyName := swiftPropertyNameFromGoName(projectedField.GetterName[3:])
	if !projectedField.IsOptional {
		g.P(indent, argumentsName, ".append(", dataName, ".", propertyName, ")")
		return
	}
	presenceName := "has" + projectedField.GetterName[3:]
	g.P(indent, "if ", dataName, ".", presenceName, " {")
	g.P(indent, "\t", argumentsName, ".append(", dataName, ".", propertyName, ")")
	g.P(indent, "} else {")
	g.P(indent, "\t", argumentsName, ".append(nil)")
	g.P(indent, "}")
}

func (e swiftEmitter) emitWrapper(file *protogen.File, models []messageModel) {
	g := e.g
	syncModels := make([]messageModel, 0, len(models))
	for _, model := range models {
		if !model.OmitSync {
			syncModels = append(syncModels, model)
		}
	}

	g.P("struct CRUD {")
	for _, model := range models {
		g.P("\tlet ", swiftPropertyNameFromGoName(model.GoName), ": ", model.TableTypeName)
	}
	g.P("\tinit(_ q: any DBTX) {")
	for _, model := range models {
		g.P("\t\tself.", swiftPropertyNameFromGoName(model.GoName), " = ", model.TableTypeName, "(q)")
	}
	g.P("\t}")
	g.P()
	g.P("\tfunc tableDescriptors() -> [GeneratedTableDescriptor] {")
	g.P("\t\treturn [")
	for _, model := range models {
		g.P("\t\t\tGeneratedTableDescriptor(tableName: ", model.GoName, "TableName, typeName: ", model.GoName, "TypeName, isCore: false, syncEnabled: ", strconv.FormatBool(!model.OmitSync), "),")
	}
	g.P("\t\t\tGeneratedTableDescriptor(tableName: coreTableDeletedName, typeName: \"\", isCore: true, syncEnabled: false),")
	g.P("\t\t\tGeneratedTableDescriptor(tableName: coreTableSyncName, typeName: \"\", isCore: true, syncEnabled: false),")
	g.P("\t\t\tGeneratedTableDescriptor(tableName: coreTableSchemaStateName, typeName: \"\", isCore: true, syncEnabled: false),")
	g.P("\t\t\tGeneratedTableDescriptor(tableName: coreTableUnknownName, typeName: \"\", isCore: true, syncEnabled: false),")
	g.P("\t\t]")
	g.P("\t}")
	g.P()
	g.P("\tprivate func dbtx() -> any DBTX {")
	g.P("\t\treturn ", swiftPropertyNameFromGoName(models[0].GoName), ".q")
	g.P("\t}")
	g.P()
	g.P("\tfunc initialize() throws {")
	for _, model := range models {
		g.P("\t\ttry ", swiftPropertyNameFromGoName(model.GoName), ".initialize()")
	}
	g.P("\t}")
	g.P()
	g.P("\tfunc writeJSONL(remote: String) throws -> String {")
	g.P("\t\tlet q = dbtx()")
	g.P("\t\tvar output = \"\"")
	for _, model := range syncModels {
		propertyName := swiftPropertyNameFromGoName(model.GoName)
		g.P("\t\tfor row in try ", propertyName, ".select() {")
		g.P("\t\t\tif !(try syncNeedsSend(q, objectID: row.id, tableName: ", model.GoName, "TableName, remote: remote, atNs: row.atNs)) {")
		g.P("\t\t\t\tcontinue")
		g.P("\t\t\t}")
		g.P("\t\t\tlet dataJSON = try marshalAnyJSON(row.data, typeName: ", model.GoName, "TypeName)")
		g.P("\t\t\toutput += try encodeJSONLRecord(JSONLRecord(id: row.id, deleted: false, atNs: row.atNs, data: dataJSON))")
		g.P("\t\t\ttry syncUpsert(q, objectID: row.id, tableName: ", model.GoName, "TableName, remote: remote, atNs: row.atNs)")
		g.P("\t\t}")
	}
	if len(syncModels) > 0 {
		args := make([]string, 0, len(syncModels))
		for _, model := range syncModels {
			args = append(args, model.GoName+"TableName")
		}
		placeholders := strings.TrimRight(strings.Repeat("?,", len(syncModels)), ",")
		g.P("\t\ttry q.withRows(\"SELECT table_name, id, at_ns FROM \\(_deletedTableName) WHERE table_name IN ("+placeholders+")\", arguments: [", strings.Join(args, ", "), "]) { rows in")
		g.P("\t\t\twhile let row = try rows.next() {")
		g.P("\t\t\t\tlet tableName = try row.string(at: 0)")
		g.P("\t\t\t\tlet id = try row.string(at: 1)")
		g.P("\t\t\t\tlet atNs = try row.int64(at: 2)")
		g.P("\t\t\t\tif !(try syncNeedsSend(q, objectID: id, tableName: tableName, remote: remote, atNs: atNs)) {")
		g.P("\t\t\t\t\tcontinue")
		g.P("\t\t\t\t}")
		g.P("\t\t\t\tlet typeName: String")
		g.P("\t\t\t\tswitch tableName {")
		for _, model := range syncModels {
			g.P("\t\t\t\tcase ", model.GoName, "TableName:")
			g.P("\t\t\t\t\ttypeName = ", model.GoName, "TypeName")
		}
		g.P("\t\t\t\tdefault:")
		g.P("\t\t\t\t\tthrow ProprDBError(\"unsupported tombstone table \\(tableName)\")")
		g.P("\t\t\t\t}")
		g.P("\t\t\t\tlet dataJSON = try marshalTypeOnlyAnyJSON(typeName: typeName)")
		g.P("\t\t\t\toutput += try encodeJSONLRecord(JSONLRecord(id: id, deleted: true, atNs: atNs, data: dataJSON))")
		g.P("\t\t\t\ttry syncUpsert(q, objectID: id, tableName: tableName, remote: remote, atNs: atNs)")
		g.P("\t\t\t}")
		g.P("\t\t}")
	}
	g.P("\t\treturn output")
	g.P("\t}")
	g.P()
	g.P("\tfunc readJSONL(remote: String, text: String) throws {")
	g.P("\t\tlet q = dbtx()")
	g.P("\t\tvar readError: Error?")
	g.P("\t\tdo {")
	g.P("\t\t\ttry ", swiftRuntimeModuleName, ".readJSONL(text: text) { record, lineNumber in")
	g.P("\t\t\t\tif record.id.isEmpty {")
	g.P("\t\t\t\t\tthrow ProprDBError(\"jsonl line \\(lineNumber) has empty id\")")
	g.P("\t\t\t\t}")
	g.P("\t\t\t\tif record.data.isEmpty {")
	g.P("\t\t\t\t\tthrow ProprDBError(\"jsonl line \\(lineNumber) has empty data\")")
	g.P("\t\t\t\t}")
	g.P("\t\t\t\tlet typeName = try typeNameFromAnyJSON(record.data)")
	g.P("\t\t\t\tswitch typeName {")
	for _, model := range models {
		propertyName := swiftPropertyNameFromGoName(model.GoName)
		g.P("\t\t\t\tcase ", model.GoName, "TypeName:")
		if model.OmitSync {
			g.P("\t\t\t\t\tlogIgnoredUnsyncedJSONLRecord(typeName: typeName, id: record.id, remote: remote, lineNumber: lineNumber)")
			g.P("\t\t\t\t\treturn")
			continue
		}
		g.P("\t\t\t\t\tlet localMax = try localMaxAtNs(q, tableName: ", model.GoName, "TableName, objectID: record.id)")
		g.P("\t\t\t\t\ttry syncUpsert(q, objectID: record.id, tableName: ", model.GoName, "TableName, remote: remote, atNs: record.atNs)")
		g.P("\t\t\t\t\tif record.atNs < localMax {")
		g.P("\t\t\t\t\t\treturn")
		g.P("\t\t\t\t\t}")
		g.P("\t\t\t\t\tif record.deleted {")
		g.P("\t\t\t\t\t\ttry ", propertyName, ".tombstoneWithAtNs(id: record.id, atNs: record.atNs)")
		g.P("\t\t\t\t\t\treturn")
		g.P("\t\t\t\t\t}")
		g.P("\t\t\t\t\tlet data = try decodeAnyJSON(record.data, as: ", swiftMessageTypeName(file, model.GoName), ".self)")
		g.P("\t\t\t\t\ttry ", propertyName, ".upsertWithAtNs(id: record.id, atNs: record.atNs, data: data)")
		g.P("\t\t\t\t\treturn")
	}
	g.P("\t\t\t\tdefault:")
	g.P("\t\t\t\t\ttry unknownInsert(q, typeName: typeName, record: record)")
	g.P("\t\t\t\t}")
	g.P("\t\t\t}")
	g.P("\t\t} catch {")
	g.P("\t\t\treadError = error")
	g.P("\t\t}")
	g.P("\t\tdo {")
	g.P("\t\t\ttry compactUnknownLatest(q)")
	g.P("\t\t} catch {")
	g.P("\t\t\tif let readError {")
	g.P("\t\t\t\tthrow ProprDBError(\"read jsonl: \\(readError) (additionally, compact unknown rows: \\(error))\")")
	g.P("\t\t\t}")
	g.P("\t\t\tthrow error")
	g.P("\t\t}")
	g.P("\t\tif let readError {")
	g.P("\t\t\tthrow readError")
	g.P("\t\t}")
	g.P("\t}")
	g.P("}")
	g.P()
}

func swiftMessageTypeName(file *protogen.File, goName string) string {
	packageName := string(file.Desc.Package())
	if packageName == "" {
		return goName
	}
	parts := strings.Split(packageName, ".")
	swiftParts := make([]string, 0, len(parts)+1)
	for _, part := range parts {
		swiftParts = append(swiftParts, swiftTypeNameSegment(part))
	}
	swiftParts = append(swiftParts, goName)
	return strings.Join(swiftParts, "_")
}

func swiftTypeNameSegment(value string) string {
	if value == "" {
		return ""
	}
	runes := []rune(strings.ToLower(value))
	runes[0] = unicode.ToUpper(runes[0])
	return string(runes)
}

func swiftPropertyNameFromGoName(value string) string {
	if value == "" {
		return value
	}
	runes := []rune(value)
	runes[0] = unicode.ToLower(runes[0])
	return string(runes)
}

func escapeSwiftStringLiteralContent(value string) string {
	replacer := strings.NewReplacer(`\`, `\\`, `"`, `\"`)
	return replacer.Replace(value)
}
